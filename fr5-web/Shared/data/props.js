/**
 * 파지점에서 **거치대 중심까지의 밀림** — 그림과 시뮬이 **같은 식**을 쓰게 한 곳에 둔다.
 *
 * 무는 벽의 길이(`graspWallLenMm`)에 **수직인 치수의 절반**만큼, **손가락 축(rz)** 방향으로.
 * ⛔ 두 곳에 각각 적었다가 한쪽만 고쳐 8mm 어긋난 적이 있다 (2026-08-31).
 *
 * @param rzDeg 파지 자세의 손목 각 (툴 X = 손가락이 벌어지는 축)
 * @returns `{ dxMm, dyMm }` — 파지점에 더하면 거치대 중심이 된다
 */
export function carrierBodyOffset(rzDeg) {
  if (!CARRIER.graspOnWall) return { dxMm: 0, dyMm: 0 };
  // 무는 벽이 85 면 수직 치수는 69, 반대면 반대다 — 이름이 아니라 **치수로** 고른다
  const perp = CARRIER.graspWallLenMm === CARRIER.dMm ? CARRIER.wMm : CARRIER.dMm;
  const half = perp / 2;
  const th = (rzDeg * Math.PI) / 180;
  // 부호 — 로봇에서 **먼 쪽**(+x 쪽)으로 몸통이 뻗는다
  const sgn = Math.cos(th) >= 0 ? 1 : -1;
  return { dxMm: sgn * half * Math.cos(th), dyMm: sgn * half * Math.sin(th) };
}

/**
 * 거치대가 바구니에 **들어가나** — 산수로 미리 답한다 (2026-08-31).
 *
 * ⛔ **손가락을 빼먹지 않는다.** 거치대만 재고 넣으면 손가락이 걸리는 순간을 못 본다.
 * `fingerThicknessMm` 이 `null` 인 동안 이 함수는 **판정을 안 낸다** (제1원칙 · 결측=차단).
 */
export function carrierFitsBasket(fingerThicknessMm = null, clearanceMm = 5) {
  const gapW = AMR_BASKET.innerWMm - CARRIER.wMm;      // 110 − 69 = 41
  const gapD = AMR_BASKET.innerDMm - CARRIER.dMm;      // 120 − 85 = 35
  const gapH = AMR_BASKET.innerHMm - CARRIER.hMm;      // 90 − 55 = 35
  const base = { gapWMm: gapW, gapDMm: gapD, gapHMm: gapH };
  if (fingerThicknessMm == null) {
    return { ...base, ok: null,
      why: '손가락 두께를 모른다 — 거치대만으로는 「들어간다」를 말할 수 없다' };
  }
  const needW = CARRIER.wMm + 2 * fingerThicknessMm + clearanceMm;
  const needD = CARRIER.dMm + 2 * fingerThicknessMm + clearanceMm;
  return { ...base,
    ok: needW <= AMR_BASKET.innerWMm && needD <= AMR_BASKET.innerDMm && CARRIER.hMm <= AMR_BASKET.innerHMm,
    needWMm: needW, needDMm: needD,
    why: `손가락 ${fingerThicknessMm}mm · 여유 ${clearanceMm}mm 기준` };
}

