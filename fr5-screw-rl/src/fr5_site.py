def j6_window(sweep_deg):
    """`sweep_deg` 만큼 **왼쪽으로** 돌리려면 시작 j6 가 어느 범위여야 하나."""
    lo = JOINT_LIMITS_DEG[5][0] + J6_MARGIN_DEG
    hi = JOINT_LIMITS_DEG[5][1] - J6_MARGIN_DEG
    return max(lo, lo + sweep_deg), hi


def wait_cap_s(j_from, j_to, vel_pct):
    """이 이동이 걸릴 시간의 상한(초). 고정값을 쓰면 느린 큰 이동이 '막혔다'로 오인된다."""
    delta = max(abs(float(t) - float(f)) for f, t in zip(j_from, j_to))
    deg_s = JOINT_DEG_S_AT_FULL * max(float(vel_pct), 1.0) / 100.0
    return (MOVE_REGISTER_S + delta / deg_s) * WAIT_MARGIN + 5.0
